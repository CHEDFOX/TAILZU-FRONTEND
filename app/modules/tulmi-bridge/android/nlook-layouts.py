#!/usr/bin/env python3
"""
THE nlook FRAGMENT KIT (NLookPlan.kt, NLookRemote.kt), generated: res/layout/nl_*.xml, from the one spec below.

    python3 app/modules/tulmi-bridge/android/nlook-layouts.py

WHY A KIT AT ALL. RemoteViews inflates only layouts compiled into the APK, so a server-sent tree is composed by adding these
tiny fragments to one another with addView. Each fragment is ONE view with the SAME root id (@+id/nl_root), which is what lets
NLookRemote set a child's own text, colour, size, margin and click on the child's own RemoteViews before it is added — a set
always lands on that fragment's own root and never on a parent's.

WHAT HAS TO BE BAKED IN, AND WHY (these are the reasons the kit is this shape, not a bigger or smaller one):

  gravity        LinearLayout's own gravity is not a method we may call remotely (RemoteViews only calls methods marked
                 @RemotableViewMethod, ref/RemoteViews.java:2058), so a container exists per nlook `align`: start, center, end.
                 On V that is ACROSS the stack, so horizontal; on H it is vertical, BY BOX — hence baselineAligned="false",
                 because iOS never aligns a row by text baseline and the two platforms must agree.
  layout_gravity a FrameLayout child's gravity comes from its own layout params, which nothing remotable sets. So a Z whose
                 align is center or end wraps each child in nl_zc_*, and the planner pays one level for it.
  layout_weight  not remotable either: a Spacer is a view with weight 1 baked in, one per axis.
  typeface       setTypeface is not remotable, and neither is auto-size. So a text fragment exists per (face, weight,
                 autosize). FACES below is the one place a bundled res/font face is wired in: until the TTFs land, `brand`,
                 `display` and `dots` resolve to `sans` in NLookPlanner.textLayout, which is what the contract already says a
                 font that cannot register does.
  scaleType      an enum setter, not remotable: one image fragment per nlook `fit`.
  clipToOutline  see base() below: the runtime call that sets a corner radius does not clip on its own.

Every fragment stays RemoteViews-safe: the launcher inflates a RemoteViews layout through a filter that admits only classes
annotated @RemoteView (ref/RemoteViews.java:359), so a plain <View> or a <Space> would be refused and the widget would not
load at all. An empty FrameLayout is the kit's box and its spacer for exactly that reason. Every id is nl_root, so there is
exactly one id in the whole kit.
"""
import os
import sys

RES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "main", "res")
OUT = os.path.join(RES, "layout")
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'

HEAD = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!--\n  GENERATED by android/nlook-layouts.py. Do not edit by hand.\n  {why}\n-->"

# THE FACES THE KIT CAN SET, and at which weights. A token with no face of its own falls to `sans` in
# NLookPlanner.textLayout, whose `when` is the matching half of this table: change one and change the other.
#
# `sans` and `mono` are the system's, so they get the whole weight range and the synthetic emphasis that goes with it.
# The three bundled faces are STATIC files (android/fonts/README.md), one file per real weight, so they get exactly the
# weights there are files for and NO textStyle: faking bold on a static face is what the design is avoiding.
FACES = {
    "sans": {"family": None, "weights": [400, 500, 600, 700, 800]},
    "mono": {"family": "monospace", "weights": [400, 500, 600, 700, 800]},
    "brand": {"files": {500: "geist_medium", 600: "geist_semibold"}},
    "display": {"files": {600: "bricolage_grotesque_semibold"}},
    "dots": {"files": {400: "doto_regular"}},
}

WEIGHTS = {
    400: {},
    500: {"fontFamily": "sans-serif-medium"},
    600: {"fontFamily": "sans-serif-medium", "textStyle": "bold"},
    700: {"textStyle": "bold"},
    800: {"fontFamily": "sans-serif-black", "textStyle": "bold"},
}

ALIGN_V = {"start": "start", "center": "center_horizontal", "end": "end"}
ALIGN_H = {"start": "top", "center": "center_vertical", "end": "bottom"}


def el(tag, attrs, why):
    lines = [HEAD.format(why=why), "<%s %s" % (tag, NS)]
    keys = sorted(attrs, key=lambda k: (0 if k == "id" else 1 if k.startswith("layout_") else 2, k))
    for k in keys:
        lines.append('    android:%s="%s"' % (k, attrs[k]))
    lines.append("    />")
    return "\n".join(lines) + "\n"


def write(name, text):
    with open(os.path.join(OUT, name + ".xml"), "w", encoding="utf-8") as f:
        f.write(text)
    return name


def base(w="wrap_content", h="wrap_content", **kw):
    # clipToOutline is baked into EVERY fragment. RemoteViews.setViewOutlinePreferredRadius only sets an
    # OutlineProvider (ref/RemoteViews.java:5621) — it does not clip — and View.setClipToOutline is not a method
    # RemoteViews may call, so a corner radius would otherwise round the shadow and leave the background square.
    # With it baked here, a radius set at apply time rounds the view and a radius of 0 leaves it exactly as it was.
    out = {"id": "@+id/nl_root", "layout_width": w, "layout_height": h, "clipToOutline": "true"}
    out.update(kw)
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    made = []

    # ---- stacks: one per axis per align, the gravity baked in
    for align, g in ALIGN_V.items():
        made.append(write("nl_v_" + align, el(
            "LinearLayout", base(orientation="vertical", gravity=g),
            "V, align %s: ACROSS the stack, so horizontal gravity." % align)))
    for align, g in ALIGN_H.items():
        made.append(write("nl_h_" + align, el(
            "LinearLayout", base(orientation="horizontal", gravity=g, baselineAligned="false"),
            "H, align %s: ACROSS the stack, so vertical gravity, BY BOX (baselineAligned false: iOS never baselines)." % align)))

    # ---- Z and its gravity wrappers
    made.append(write("nl_z", el("FrameLayout", base(), "Z: children sit top-leading, a FrameLayout's own default.")))
    for align, g in (("center", "center"), ("end", "bottom|end")):
        made.append(write("nl_zc_" + align, el(
            "FrameLayout", base(layout_gravity=g),
            "One child of a Z aligned %s. Nothing remotable sets a FrameLayout child's gravity, so it is baked here and the "
            "planner pays one level for it." % align)))

    # ---- spacers: weight is not remotable, so it is baked, one per axis
    made.append(write("nl_spacer_v", el(
        "FrameLayout", base(w="match_parent", h="0dp", layout_weight="1"),
        "Spacer in a V: weight 1, baked. An empty FrameLayout, because a plain View is not a @RemoteView class.")))
    made.append(write("nl_spacer_h", el(
        "FrameLayout", base(w="0dp", h="match_parent", layout_weight="1"),
        "Spacer in an H: weight 1, baked. An empty FrameLayout, for the same reason.")))

    # ---- a plain box: Shape rect, capsule and circle, and the Kit pills. Tinted and given an outline radius at apply time.
    made.append(write("nl_box", el(
        "FrameLayout", base(w="match_parent", h="8dp"),
        "Shape rect / capsule / circle and the Kit pills: a tinted, empty FrameLayout with an outline radius, never a "
        "bitmap. The planner always decides both dimensions, because an empty frame measures to nothing.")))

    # ---- images: one per fit, because setScaleType is an enum setter and not remotable
    for fit, scale in (("fit", "fitCenter"), ("fill", "centerCrop"), ("stretch", "fitXY")):
        made.append(write("nl_img_" + fit, el(
            "ImageView", base(scaleType=scale, adjustViewBounds="true", contentDescription="@null",
                              importantForAccessibility="no"),
            "Image / Bot / Shape path / dots / ring, fit %s." % fit)))
    made.append(write("nl_bar", el(
        "ImageView", base(w="match_parent", h="4dp", scaleType="fitXY", contentDescription="@null",
                          importantForAccessibility="no"),
        "Bar: the stage bar, painted once at the bar's own width so its stripes keep their angle.")))

    # ---- a live timer: the one thing in a widget that moves between entries without spending a redraw
    made.append(write("nl_chrono", el(
        "Chronometer", base(includeFontPadding="false"),
        "Text with `timer` or `countdown`: a Chronometer, so minutes count on with no redraw budget spent.")))

    # ---- text: one per (face, weight, autosize)
    for face, spec in FACES.items():
        files = spec.get("files")
        weights = spec.get("weights") or sorted(files)
        for weight in weights:
            for auto in (False, True):
                attrs = base(ellipsize="end", includeFontPadding="false")
                if files:
                    # A bundled file carries its own weight. No synthetic bold over it, and no system family under it.
                    attrs["fontFamily"] = "@font/" + files[weight]
                else:
                    if spec.get("family"):
                        attrs["fontFamily"] = spec["family"]
                    attrs.update(WEIGHTS[weight])
                if auto:
                    # Auto-size is not remotable either, so the shrink-to-fit variant is its own fragment.
                    attrs.update({"autoSizeTextType": "uniform", "autoSizeMinTextSize": "9sp", "autoSizeStepGranularity": "1sp"})
                name = "nl_t_%s_%d%s" % (face, weight, "_auto" if auto else "")
                made.append(write(name, el(
                    "TextView", attrs,
                    "Text: face %s, weight %d%s." % (face, weight, ", shrink to fit" if auto else ""))))

    print("wrote %d layouts to %s" % (len(made), OUT))
    for name in made:
        print("  " + name + ".xml")


if __name__ == "__main__":
    main()
