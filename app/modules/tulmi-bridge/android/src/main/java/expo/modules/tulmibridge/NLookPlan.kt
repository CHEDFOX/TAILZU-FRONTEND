package expo.modules.tulmibridge

/**
 * nlook on Android, part two: THE PLANNER. A node tree in, a tree of fragment operations out.
 *
 * PURE KOTLIN ON PURPOSE. Nothing here imports android.* or org.json, so every rule below is testable on the JVM
 * (src/test/java/.../NLookPlanTest.kt) against the shared fixtures' cases. NLookRemote.kt turns a plan into RemoteViews;
 * NLookPaint.kt draws the bitmaps a plan asks for. Neither decides anything.
 *
 * WHY A PLANNER AT ALL. RemoteViews can only inflate layouts compiled into the APK, so a server tree is composed from a kit of
 * tiny fragment layouts added with addView (res/layout/nl_*.xml, generated by android/nlook-layouts.py). The launcher unpacks
 * that tree in ITS process and throws "Too many nested views." past MAX_NESTED_VIEWS = 10 (ref/RemoteViews.java:234, :6166) —
 * an exception our code can never catch, and the person sees "Problem loading widget". So the planner counts REMOTEVIEWS
 * LEVELS itself, caps at 8 including the size-map level and every wrapper fragment, and flattens wherever it can:
 *
 *   Each    expands INLINE into its parent's children. It is never a container, so a list costs no level.
 *   Button  puts its click on its child's own view. No wrapper frame, no level.
 *   Grid    one row becomes a single H (one level); more rows become a V of H rows (two).
 *   Z       `align` start costs nothing. center and end cost one wrapper per child, because RemoteViews cannot set a
 *           FrameLayout child's layout_gravity; if that wrapper would not fit the budget, the Z draws start.
 *   border  one wrapper level, filled with the ring colour, holding the node inset by its width. The same price today's
 *           pill already pays for its own frame. When the level does not fit, the node draws without its ring.
 *
 * Over the cap, a subtree draws its own `fallback` node, then nothing — never a half-drawn tree, never an exception.
 */

// ====================================================================================================== what a plan is

/** Where one draw is happening. Every `if` key format 1 knows is answered from here or from NLookSource. */
internal class NLookWhere(
  /** small | medium | large. The Android widget has no accessory families. */
  val family: String,
  val night: Boolean,
  /** The glance's case as of this draw's minute (needs | working | done | quiet). */
  val case: String,
  /** Whether the widgets' own token can answer a needs item right here. */
  val canAnswer: Boolean,
  val widthDp: Float,
  val heightDp: Float,
)

/** Inside an `Each`: which list, which copy, and the name its children bind it by ("it"). */
internal class NLookScope(val list: String, val index: Int, val alias: String)

/**
 * Everything the planner needs from the glance, the palette and the files on disk, behind one door so the planner stays pure.
 * NLookBind.kt is the real one; a test passes a fake.
 */
internal interface NLookSource {
  /** A template with its `{{…}}` filled. `hide` is true when every slot resolved empty and no words are left. */
  fun fill(template: String, scope: NLookScope?): NLookFilled

  /** Whether anything in this template may be private (BIND_PATHS `sensitive`). */
  fun sensitive(template: String, scope: NLookScope?): Boolean

  /** `if: { has: "lastDone.pr" }` — whether that path resolves to something non-empty. */
  fun has(path: String, scope: NLookScope?): Boolean

  /** How many copies an `Each` has; 0 for a list this build does not know. */
  fun listCount(path: String): Int

  /** The colour grammar: #hex, a palette role, $color, $bot.<slug>, each with an optional @alpha. Null for unknown. */
  fun ink(token: String, scope: NLookScope?): NLookInk?

  /** The file on disk for an art key ("art:dusk.sky", "face:code", "bot:code.wave@0.6"), or null when it is not there. */
  fun art(key: String, scope: NLookScope?): String?

  /** A bundled drawable's resource name for `pose:` and `sym:`, or null. */
  fun bundled(src: String): String?

  /**
   * A BOT'S OWN FACE FILE (files/widget-faces/<face>.png), by its slug, or null before the app has downloaded one. It is
   * what a Bot node draws when no still of that bot is on this phone yet: a card shows the bot whose card it is.
   */
  fun faceArt(slug: String?): String?

  /** A date path as wall-clock ms, for a timer. Null when there is none. */
  fun dateMs(path: String, scope: NLookScope?): Long?

  /**
   * Which bot `$bot` means here: the Each copy's own, else the running job's, else the first needs item's, else the last
   * done. Null when the glance names none, and a Bot node then draws its fallback. `$bot` is NOT a template, so it never
   * went through `fill` — doing that left the key as the literal "bot:$bot.work", which is on no disk anywhere.
   */
  fun botFor(scope: NLookScope?): String?

  /** `relative`: that date in words as of this draw ("4 min"), already in the person's language. Empty when there is none. */
  fun relative(path: String, scope: NLookScope?): String
}

/** A filled template. A Text whose every slot resolved empty hides, so a raw "{n}" never prints. */
internal class NLookFilled(val text: String, val hide: Boolean)

/** A colour in both themes. Kept separate from WidgetInk's `Ink` so the planner stays free of android.graphics. */
internal class NLookInk(val light: Int, val dark: Int)

/** One click a plan may carry: open a vetted link, or answer a needs item with the widgets' own narrow token. */
internal class NLookClick(val open: String?, val item: String?, val action: String?, val slot: Int)

/** A bitmap the painter must draw before the plan is applied. `kind` is one of the PAINT_* names below. */
internal class NLookPaintReq(
  val kind: String,
  val wDp: Float,
  val hDp: Float,
  val fill: NLookInk?,
  val stroke: NLookInk?,
  val strokeDp: Float,
  /** path: the `d` strings, at most 12, each at most 900 characters. */
  val paths: List<String>,
  val viewBox: FloatArray?,
  /** dots: how many across and down, their spacing and radius. */
  val grid: Int,
  val spacingDp: Float,
  val dotDp: Float,
  /** bar and ring: where it has got to. */
  val value: Int,
  val of: Int,
  /** art: the file on disk, or a bundled drawable's resource name. */
  val file: String?,
  val drawable: String?,
  /** A stable key, so one Bitmap object is painted once per (key, px) and reused across every size of this widget. */
  val key: String,
  /** bar: the stage names drawn under it, when the design named exactly `of` of them. */
  val labels: NLookBarLabels? = null,
)

internal const val PAINT_ART = "art"
internal const val PAINT_PATH = "path"
internal const val PAINT_DOTS = "dots"
internal const val PAINT_RING = "ring"
internal const val PAINT_BAR = "bar"

/** One set to apply to one fragment's own root view. */
internal sealed class NLookSet {
  class Words(val value: String) : NLookSet()
  class TextSizeDp(val dp: Float) : NLookSet()
  class TextColor(val ink: NLookInk) : NLookSet()
  class MaxLines(val n: Int) : NLookSet()
  /** start | center | end, as TextView gravity (which IS remotable). */
  class TextAlign(val align: String) : NLookSet()
  class Track(val em: Float) : NLookSet()
  class AllCaps(val on: Boolean) : NLookSet()
  class Background(val ink: NLookInk) : NLookSet()
  class Corner(val dp: Float) : NLookSet()
  class PadDp(val pad: FloatArray) : NLookSet()
  /** null leaves the dimension as the fragment's XML set it; fill is match_parent, fit is wrap_content. */
  class WidthDp(val dp: Float?, val fill: Boolean, val fit: Boolean) : NLookSet()
  class HeightDp(val dp: Float?, val fill: Boolean, val fit: Boolean) : NLookSet()
  /** All four sides, because a `border`'s inset needs end and bottom as well as a gap's start and top. */
  class MarginDp(val start: Float, val top: Float, val end: Float = 0f, val bottom: Float = 0f) : NLookSet()
  /** Text and timers only: TextView.setMaxWidth / setMaxHeight ARE remotable; a frame cannot be given a maximum. */
  class MaxWidthDp(val dp: Float) : NLookSet()
  class MaxHeightDp(val dp: Float) : NLookSet()
  /**
   * Only ever on a picture. `opacity` on anything else is folded into the colours the planner already sends, because
   * View.setAlpha is not a method RemoteViews may call and a method it may not call kills the whole widget.
   */
  class ImageAlpha(val value: Float) : NLookSet()
  class Tint(val ink: NLookInk) : NLookSet()
  /** What a screen reader says for a picture that carries meaning: today, the Bar's current stage. */
  class Describe(val words: String) : NLookSet()
  class Paint(val req: NLookPaintReq) : NLookSet()
  class Click(val click: NLookClick) : NLookSet()
  /** A live timer: Chronometer counting up from (or down to) this wall-clock ms. */
  class Timer(val baseMs: Long, val countDown: Boolean) : NLookSet()
}

/** One fragment: which layout to inflate, what to set on its own root, and what goes inside it. */
internal class NLookPlanNode(val layout: String, val sets: List<NLookSet>, val children: List<NLookPlanNode>)

/** What one root planned to, and what had to be given up on the way. `levels` and `views` are what the JVM tests assert. */
internal class NLookPlanResult(val root: NLookPlanNode, val levels: Int, val views: Int, val paints: List<NLookPaintReq>)

// ====================================================================================================== the planner

internal class NLookPlanner(
  private val src: NLookSource,
  private val where: NLookWhere,
  /** RemoteViews levels this tree may use: NLookLimits.LEVELS minus the size-map level the caller will add. */
  private val levels: Int = NLookLimits.LEVELS - 1,
) {
  private var views = 0
  private val paints = ArrayList<NLookPaintReq>()
  private var slot = 0

  /**
   * THE NEAREST BACKGROUND AT OR ABOVE THE NODE BEING PLANNED, as the design wrote it, `@alpha` and all. Two rules read
   * it and both are in the contract:
   *   - a Text, timer or `sym:` Image with no `tint` is `ground` over `ink` or `accent`, and `ink` over anything else;
   *   - a `border`'s wrapper needs to know what paints the middle, since the ring colour is behind the node.
   * Carried as a field rather than a parameter on nine functions, saved and restored around each node in `one`, which is
   * depth-first and single-threaded. ROLES, never luma, so light and dark give the same answer as iOS gives.
   */
  private var nearBg: String? = null

  /** Plan one root. Null when nothing could be drawn at all: the caller then draws today's hand-written view. */
  fun plan(root: NLookNode): NLookPlanResult? {
    views = 0
    paints.clear()
    slot = 0
    nearBg = null
    // A WIDGET ROOT WITH NO `bg` IS `ground` (H16-Q1), the one rule all three renderers follow: iPhone hands it to the
    // container, the preview paints it, every bundled root says so outright. Android was the renderer that differed —
    // the kit fragments carry no background of their own, so such a root came out see-through on a home screen.
    val node = if (root.type == "Each") wrap(root) else grounded(root)
    val planned = one(node, 1, AXIS_V, null) ?: return null
    return NLookPlanResult(planned, depth(planned), views, ArrayList(paints))
  }

  /** The root as if it had said `bg: "ground"`, when it said no `bg` at all. Everything else about it is untouched. */
  private fun grounded(root: NLookNode): NLookNode {
    if (root.style["bg"] != null) return root
    val style = HashMap<String, Any?>(root.style)
    style["bg"] = "ground"
    return NLookNode(root.type, root.props, style, root.children, root.cond, root.fallback)
  }

  /** An `Each` as a root has no parent to expand into, so it gets a V of its own. */
  private fun wrap(each: NLookNode): NLookNode =
    NLookNode(type = "V", props = mapOf("gap" to 0.0, "align" to "start"), children = listOf(each))

  // ---------------------------------------------------------------- one node

  /**
   * One node at `level`. Returns null when the node draws nothing at all — which is a normal outcome, not an error: an `if`
   * that does not match, a bound Text that resolved empty, art that is not on disk yet.
   *
   * Two things happen around the node itself here, both of them about what is BEHIND it: the nearest background is carried
   * down for the duration, and a `border` is drawn as one wrapper level once the rest of the node is planned and its real
   * depth is known.
   */
  private fun one(node: NLookNode, level: Int, axis: Int, scope: NLookScope?): NLookPlanNode? {
    val outer = nearBg
    nlStr(node.style["bg"])?.let { nearBg = it }
    return try {
      bordered(node, dispatch(node, level, axis, scope), level, scope)
    } finally {
      nearBg = outer
    }
  }

  /**
   * A `border`, as one extra RemoteViews level: a wrapper filled with the border colour, holding the node inset by `width`
   * on all four sides, with corner `max(0, corner - width)` and the fill that was going to be behind it anyway. No drawable
   * per (colour, width), and it works for any corner.
   *
   * It is the FIRST thing given up, and for two reasons that are both about drawing something rather than nothing:
   *   - the level must fit under the cap, counted against the subtree's real depth now that it is planned;
   *   - there must be a fully opaque fill to put in the middle, the node's own `bg` or the nearest one above it, in BOTH
   *     schemes. Without one, the ring colour would show through the node instead of around it.
   *
   * The ring is drawn INSIDE the node's own frame, which is what iPhone's `strokeBorder` does and what today's ImageView
   * ring does, so a bordered node is exactly the size it was before it had a ring. DEVICE CHECK (SPEC §9): `x0.base`
   * medium's secondary pill must be the same size as today's `tailzu_widget_pill_ring` pill, light and dark.
   */
  private fun bordered(node: NLookNode, planned: NLookPlanNode?, level: Int, scope: NLookScope?): NLookPlanNode? {
    if (planned == null) return null
    val border = node.style["border"] as? Map<*, *> ?: return planned
    // 0 to 8, defaulting to 1, exactly as iPhone reads it (NLookModel.swift). With a different default a border with no
    // width would draw a hairline there and nothing here.
    val width = (nlNum(border["width"]) ?: 1.0).toFloat().coerceIn(0f, 8f)
    if (width <= 0f) return planned
    if (level + depth(planned) > levels || views >= NLookLimits.VIEWS_PER_SIZE) return planned
    val ink = nlStr(border["color"])?.let { src.ink(it, scope) } ?: return planned
    val fill = nlStr(node.style["bg"]) ?: nearBg ?: return planned
    val under = src.ink(fill, scope) ?: return planned
    if (!opaque(under.light) || !opaque(under.dark)) return planned
    val corner = (nlNum(node.style["corner"]) ?: 0.0).toFloat().coerceIn(0f, 120f)
    val wrapper = ArrayList<NLookSet>()
    wrapper.add(NLookSet.Background(ink))
    if (corner > 0f) wrapper.add(NLookSet.Corner(corner))
    // The ring takes the node's own outer size; the node fills what is left inside the inset.
    size(node.style["w"], true, wrapper)
    size(node.style["h"], false, wrapper)
    // Appended after the node's own style, so these win: a set is applied in order and the last one lands.
    val inner = ArrayList<NLookSet>(planned.sets)
    inner.add(NLookSet.MarginDp(width, width, width, width))
    // These two matter only when the node has a fixed `w`/`h`, which the wrapper has just taken for itself: the node then
    // fills what is left inside the inset. A wrap-sized node is measured AT_MOST by a FrameLayout holding one child and
    // keeps its own size either way — a FrameLayout only re-measures match_parent children with EXACTLY when it has two
    // or more of them.
    inner.add(NLookSet.WidthDp(null, fill = true, fit = false))
    inner.add(NLookSet.HeightDp(null, fill = true, fit = false))
    inner.add(NLookSet.Corner((corner - width).coerceAtLeast(0f)))
    inner.add(NLookSet.Background(under))
    // The ring is drawn INSIDE the node's own frame, as iPhone's `strokeBorder` does, so a wrap-sized node keeps the size
    // it has today. The inset margin above would otherwise push the outer frame out by 2 * width on both axes, which is a
    // visible change in a stage that promised none. Take the margin back out of the node's own padding.
    val pad = nlPad(node.style["pad"]) ?: FloatArray(4)
    inner.add(NLookSet.PadDp(FloatArray(4) { (pad[it] - width).coerceAtLeast(0f) }))
    views++
    return NLookPlanNode("nl_z", wrapper, listOf(NLookPlanNode(planned.layout, inner, planned.children)))
  }

  private fun opaque(color: Int): Boolean = ((color ushr 24) and 0xFF) == 0xFF

  private fun dispatch(node: NLookNode, level: Int, axis: Int, scope: NLookScope?): NLookPlanNode? {
    if (level > levels || views >= NLookLimits.VIEWS_PER_SIZE) return fallbackOf(node, level, axis, scope)
    if (!matches(node.cond, scope)) return null
    val made = when (node.type) {
      "V" -> stack(node, level, AXIS_V, scope)
      "H" -> stack(node, level, AXIS_H, scope)
      "Z" -> overlay(node, level, scope)
      "Grid" -> grid(node, level, scope)
      "Spacer" -> spacer(node, axis)
      "Text" -> text(node, scope)
      "Image" -> image(node, scope)
      "Bot" -> bot(node, scope)
      "Shape" -> shape(node, scope)
      "Bar" -> bar(node, scope)
      "Ring" -> ring(node, scope)
      "Kit" -> kit(node, level, scope)
      "Button" -> button(node, level, axis, scope)
      // An Each reaching here means it was not expanded by a parent: draw it inside a V of its own.
      "Each" -> one(wrap(node), level, axis, scope)
      // Unknown type: its fallback, then nothing. This is how a format-2 design still reads on a format-1 build.
      else -> null
    }
    return made ?: fallbackOf(node, level, axis, scope)
  }

  /** The node's own `fallback`, planned in its place. Guarded so a fallback that is itself too deep does not loop. */
  private fun fallbackOf(node: NLookNode, level: Int, axis: Int, scope: NLookScope?): NLookPlanNode? {
    val f = node.fallback ?: return null
    if (level > levels || views >= NLookLimits.VIEWS_PER_SIZE) return null
    if (f.type == node.type && f.children.isNotEmpty()) return null
    return one(f, level, axis, scope)
  }

  // ---------------------------------------------------------------- containers

  private fun stack(node: NLookNode, level: Int, axis: Int, scope: NLookScope?): NLookPlanNode? {
    val align = nlAlign(node.props["align"])
    val gap = (nlNum(node.props["gap"]) ?: 0.0).toFloat().coerceIn(0f, 64f)
    val layout = (if (axis == AXIS_H) "nl_h_" else "nl_v_") + align
    val sets = ArrayList<NLookSet>()
    style(node, sets, scope)
    views++
    val kids = children(node.children, level + 1, axis, scope, gap)
    // An empty container that paints nothing is not a view: give the count back, so `views` is always what was KEPT.
    if (kids.isEmpty() && node.style["bg"] == null) {
      views--
      return null
    }
    return NLookPlanNode(layout, sets, kids)
  }

  /**
   * A Z stack. Children sit top-leading, which is a FrameLayout's own default and costs nothing. `center` and `end` need a
   * gravity-baked wrapper per child, because RemoteViews has no way to set a child's layout_gravity; when that wrapper does
   * not fit the level budget the stack draws `start` rather than losing the children.
   */
  private fun overlay(node: NLookNode, level: Int, scope: NLookScope?): NLookPlanNode? {
    val align = nlAlign(node.props["align"])
    val wrapper = if (align == "start") null else "nl_zc_$align"
    val room = wrapper != null && level + 2 <= levels
    val sets = ArrayList<NLookSet>()
    style(node, sets, scope)
    views++
    val inner = children(node.children, level + 1 + (if (room) 1 else 0), AXIS_Z, scope, 0f)
    val kids = if (!room || wrapper == null) inner else inner.map { NLookPlanNode(wrapper, emptyList(), listOf(it)) }
    if (kids.isEmpty() && node.style["bg"] == null) {
      views--
      return null
    }
    // Each gravity wrapper is a real view in the launcher's tree, so it is counted as one.
    if (room && wrapper != null) views += kids.size
    return NLookPlanNode("nl_z", sets, kids)
  }

  /**
   * A Grid of `cols`. One row is a single H — one level, which is the whole point of flattening it. More rows are a V of H
   * rows: two levels, and still no per-cell wrapper.
   */
  private fun grid(node: NLookNode, level: Int, scope: NLookScope?): NLookPlanNode? {
    val cols = (nlInt(node.props["cols"]) ?: 1).coerceIn(1, 4)
    val gap = (nlNum(node.props["gap"]) ?: 0.0).toFloat().coerceIn(0f, 64f)
    val flat = expand(node.children, scope)
    if (flat.isEmpty()) return null
    val sets = ArrayList<NLookSet>()
    style(node, sets, scope)
    if (flat.size <= cols) {
      views++
      val kids = plot(flat, level + 1, AXIS_H, scope, gap)
      if (kids.isEmpty()) {
        views--
        return null
      }
      return NLookPlanNode("nl_h_start", sets, kids)
    }
    views++
    val rows = ArrayList<NLookPlanNode>()
    var i = 0
    var first = true
    while (i < flat.size && views < NLookLimits.VIEWS_PER_SIZE) {
      val slice = flat.subList(i, minOf(i + cols, flat.size))
      views++
      val cells = plot(slice, level + 2, AXIS_H, scope, gap)
      if (cells.isNotEmpty()) {
        val rowSets = if (first) emptyList() else listOf<NLookSet>(NLookSet.MarginDp(0f, gap))
        rows.add(NLookPlanNode("nl_h_start", rowSets, cells))
        first = false
      } else {
        views--
      }
      i += cols
    }
    if (rows.isEmpty()) {
      views--
      return null
    }
    return NLookPlanNode("nl_v_start", sets, rows)
  }

  /** A child list: `Each` expanded inline first, then each one planned, then `gap` applied as a margin before each but the first. */
  private fun children(list: List<NLookNode>, level: Int, axis: Int, scope: NLookScope?, gap: Float): List<NLookPlanNode> =
    plot(expand(list, scope), level, axis, scope, gap)

  private fun plot(list: List<Pair<NLookNode, NLookScope?>>, level: Int, axis: Int, scope: NLookScope?, gap: Float): List<NLookPlanNode> {
    val out = ArrayList<NLookPlanNode>()
    for (entry in list) {
      if (views >= NLookLimits.VIEWS_PER_SIZE) break
      val planned = one(entry.first, level, axis, entry.second ?: scope) ?: continue
      if (gap > 0f && out.isNotEmpty()) {
        val sets = ArrayList<NLookSet>(planned.sets)
        sets.add(if (axis == AXIS_H) NLookSet.MarginDp(gap, 0f) else NLookSet.MarginDp(0f, gap))
        out.add(NLookPlanNode(planned.layout, sets, planned.children))
      } else {
        out.add(planned)
      }
    }
    return out
  }

  /**
   * `Each` is a bounded repeat over data, never a loop: it expands INLINE into its parent's children, so a list of eight
   * costs eight views and not one level. At most 8 copies on a widget, whatever the design asks for.
   */
  private fun expand(list: List<NLookNode>, scope: NLookScope?): List<Pair<NLookNode, NLookScope?>> {
    val out = ArrayList<Pair<NLookNode, NLookScope?>>()
    for (node in list) {
      if (node.type != "Each") {
        out.add(Pair(node, scope))
        continue
      }
      if (!matches(node.cond, scope)) continue
      val of = nlStr(node.props["of"]) ?: continue
      val alias = nlStr(node.props["as"]) ?: "it"
      val asked = (nlInt(node.props["max"]) ?: NLookLimits.EACH_COPIES).coerceIn(0, NLookLimits.EACH_COPIES)
      val have = src.listCount(of)
      val copies = minOf(asked, have)
      for (i in 0 until copies) {
        val inner = NLookScope(of, i, alias)
        for (kid in node.children) {
          if (out.size >= NLookLimits.VIEWS_PER_SIZE) break
          out.add(Pair(kid, inner))
        }
      }
    }
    return out
  }

  /** A Button is its child with a click on it: no wrapper frame, no level. */
  private fun button(node: NLookNode, level: Int, axis: Int, scope: NLookScope?): NLookPlanNode? {
    val child = node.children.firstOrNull() ?: return null
    val planned = one(child, level, axis, scope) ?: return null
    val click = clickOf(node, scope) ?: return planned
    val sets = ArrayList<NLookSet>(planned.sets)
    sets.add(NLookSet.Click(click))
    return NLookPlanNode(planned.layout, sets, planned.children)
  }

  /**
   * A click, or null. A link opens only our own scheme or the one https shape today's allow-list permits, checked here as
   * well as on the server: a design can never make a widget open another app.
   */
  private fun clickOf(node: NLookNode, scope: NLookScope?): NLookClick? {
    slot++
    val act = node.props["act"] as? Map<*, *>
    if (act != null) {
      if (!where.canAnswer) return null
      val item = src.fill(nlText(act["item"]), scope).text
      val action = src.fill(nlText(act["action"]), scope).text
      if (item.isEmpty() || action.isEmpty()) return null
      return NLookClick(null, item, action, slot)
    }
    val open = src.fill(nlText(node.props["open"]), scope).text
    if (open.isEmpty() || !allowedLink(open)) return null
    return NLookClick(open, null, null, slot)
  }

  // ---------------------------------------------------------------- leaves

  private fun spacer(node: NLookNode, axis: Int): NLookPlanNode {
    val min = (nlNum(node.props["min"]) ?: 0.0).toFloat().coerceIn(0f, 400f)
    views++
    val sets = ArrayList<NLookSet>()
    if (min > 0f) {
      if (axis == AXIS_H) sets.add(NLookSet.WidthDp(min, fill = false, fit = false))
      else sets.add(NLookSet.HeightDp(min, fill = false, fit = false))
    }
    return NLookPlanNode(if (axis == AXIS_H) "nl_spacer_h" else "nl_spacer_v", sets, emptyList())
  }

  private fun text(node: NLookNode, scope: NLookScope?): NLookPlanNode? {
    val timer = nlStr(node.props["timer"]) ?: nlStr(node.props["countdown"])
    if (timer != null) return chrono(node, timer, nlStr(node.props["countdown"]) != null, scope)
    val relative = nlStr(node.props["relative"])
    val filled = if (relative != null) {
      val words = src.relative(relative, scope)
      NLookFilled(words, words.isEmpty())
    } else {
      src.fill(nlText(node.props["text"]), scope)
    }
    if (filled.hide || filled.text.isEmpty()) return null
    val size = (nlNum(node.props["size"]) ?: 13.0).toFloat().coerceIn(6f, 72f)
    val weight = (nlInt(node.props["weight"]) ?: 400).coerceIn(400, 800)
    val auto = (nlNum(node.props["minScale"]) ?: 1.0) < 1.0
    val mono = nlStr(node.props["digits"]) == "mono"
    val layout = textLayout(if (mono) "mono" else nlStr(node.props["font"]), weight, auto)
    val sets = ArrayList<NLookSet>()
    sets.add(NLookSet.Words(filled.text))
    sets.add(NLookSet.TextSizeDp(size))
    sets.add(NLookSet.TextColor(fade(words(node, scope), opacity(node))))
    sets.add(NLookSet.MaxLines((nlInt(node.props["lines"]) ?: 1).coerceIn(1, 8)))
    sets.add(NLookSet.TextAlign(nlAlign(node.props["align"])))
    nlNum(node.props["track"])?.let { sets.add(NLookSet.Track(it.toFloat().coerceIn(-0.2f, 0.4f))) }
    if (nlStr(node.props["case"]) == "upper") sets.add(NLookSet.AllCaps(true))
    style(node, sets, scope)
    ceiling(node, sets)
    views++
    return NLookPlanNode(layout, sets, emptyList())
  }

  /**
   * THE COLOUR OF WORDS. `tint` when the design gives one, in the usual colour grammar — a token that is not a colour comes
   * back as `ink`, which is what the contract calls an issue rather than a reason to lose the words.
   *
   * With no `tint`, ONE rule, and it is the same rule on iPhone: `ground` when the nearest `bg` at or above this node is the
   * ROLE `ink` or `accent` (with or without an `@alpha`), else `ink`. Roles and never luma, so the two platforms cannot
   * disagree, and a label inside a filled pill is never ink on ink. The same answer serves a timer and a `sym:` Image.
   */
  private fun words(node: NLookNode, scope: NLookScope?): NLookInk {
    nlStr(node.props["tint"])?.let { token -> src.ink(token, scope)?.let { return it } }
    return src.ink(onInk(), scope) ?: NLookInk(0, 0)
  }

  private fun onInk(): String {
    // The ROLE, with any `@alpha` dropped: "ink@0.6" is still a filled ink pill, and so are its words' ground.
    val bg = nearBg?.substringBefore("@")?.trim() ?: return "ink"
    return if (bg == "ink" || bg == "accent") "ground" else "ink"
  }

  /**
   * `maxW` / `maxH`, on a Text or a timer and nowhere else. TextView.setMaxWidth and setMaxHeight ARE @RemotableViewMethod;
   * on a frame the same call would throw inside the launcher, where nothing of ours can catch it, so every other node
   * ignores them and sets `w`/`h` instead.
   */
  private fun ceiling(node: NLookNode, sets: ArrayList<NLookSet>) {
    nlNum(node.style["maxW"])?.let { sets.add(NLookSet.MaxWidthDp(it.toFloat().coerceIn(0f, 2000f))) }
    nlNum(node.style["maxH"])?.let { sets.add(NLookSet.MaxHeightDp(it.toFloat().coerceIn(0f, 2000f))) }
  }

  /** A live timer: the one thing in a widget that changes on its own between entries (Chronometer, no redraw budget spent). */
  private fun chrono(node: NLookNode, path: String, down: Boolean, scope: NLookScope?): NLookPlanNode? {
    val base = src.dateMs(path, scope) ?: return null
    val sets = ArrayList<NLookSet>()
    sets.add(NLookSet.Timer(base, down))
    sets.add(NLookSet.TextSizeDp((nlNum(node.props["size"]) ?: 13.0).toFloat().coerceIn(6f, 72f)))
    sets.add(NLookSet.TextColor(fade(words(node, scope), opacity(node))))
    style(node, sets, scope)
    ceiling(node, sets)
    views++
    return NLookPlanNode("nl_chrono", sets, emptyList())
  }

  private fun image(node: NLookNode, scope: NLookScope?): NLookPlanNode? {
    val raw = nlStr(node.props["src"]) ?: return null
    val src1 = src.fill(raw, scope).text
    val size = (nlNum(node.props["size"]) ?: 24.0).toFloat().coerceIn(4f, 400f)
    val file = src.art(src1, scope)
    val drawable = if (file == null) src.bundled(src1) else null
    // A `sym:` glyph with no tint of its own takes the same colour words would: an icon inside a filled pill is a label.
    val symbol = src1.startsWith("sym:")
    if (file == null && drawable == null) {
      // Missing art uses `alt` (a bundled pose or symbol), then it hides. The widget never fetches anything.
      val altSrc = nlStr(node.props["alt"])
      val alt = altSrc?.let { src.bundled(it) } ?: return null
      return picture(
        node, NLookPaintReq(PAINT_ART, size, size, null, null, 0f, emptyList(), null, 0, 0f, 0f, 0, 0, null, alt, alt),
        scope, size, if (altSrc.startsWith("sym:")) onInk() else null,
      )
    }
    val key = file ?: drawable ?: return null
    return picture(
      node, NLookPaintReq(PAINT_ART, size, size, null, null, 0f, emptyList(), null, 0, 0f, 0f, 0, 0, file, drawable, key),
      scope, size, if (symbol) onInk() else null,
    )
  }

  /**
   * The dotted bot as a STILL. The phone drew it from the bots' own catalog (botArt.ts) into the art channel, so here it is
   * only an art key: bot:<who>.<moment>@<at>.
   *
   * NOT ON DISK YET IS STILL THAT BOT'S CARD. The still is the first choice, not the only one: after it comes the bot's own
   * face file, and after that a disc in its own colour. The node's `fallback` is a mascot pose in every design the catalog
   * ships, and a card may not show the mascot in place of the bot it is about — so the fallback is reached only when NO bot
   * is bound at all, which is the one case where there is nobody to draw.
   */
  private fun bot(node: NLookNode, scope: NLookScope?): NLookPlanNode? {
    val asked = nlStr(node.props["who"]) ?: "\$bot"
    val moment = nlStr(node.props["moment"]) ?: "rest"
    val at = (nlNum(node.props["at"]) ?: 0.0).coerceIn(0.0, 1.0)
    val size = (nlNum(node.props["size"]) ?: 32.0).toFloat().coerceIn(8f, 400f)
    // `$bot` is the BOUND bot, not a template: every Bot node in the catalog writes it, and putting it through `fill`
    // left the literal "$bot" in the key, so no still on disk was ever found. With no bot bound at all, the node's own
    // fallback draws — never a guessed slug, which would look up a picture of the wrong bot.
    val who = if (asked.isEmpty() || asked == "\$bot") src.botFor(scope) ?: return null else src.fill(asked, scope).text
    // A slug and nothing else: anything else names no still on disk, and it would reach the colour grammar as a token.
    if (!BOT_SLUG.matches(who)) return null
    val key = "bot:" + who + "." + moment + "@" + trim2(at)
    val file = src.art(key, scope) ?: src.faceArt(who)
    if (file != null) {
      return picture(node, NLookPaintReq(PAINT_ART, size, size, null, null, 0f, emptyList(), null, 0, 0f, 0f, 0, 0, file, null, file), scope, size)
    }
    return disc(node, who, size, scope)
  }

  /**
   * A bot with no picture on this phone at all: a disc in its OWN colour, which is the last thing every card falls to on
   * both platforms. A plain tinted box, so it costs no bitmap and no extra level.
   */
  private fun disc(node: NLookNode, who: String, size: Float, scope: NLookScope?): NLookPlanNode? {
    val ink = src.ink("\$bot.$who", scope) ?: src.ink("ink", scope) ?: return null
    val sets = ArrayList<NLookSet>()
    sets.add(NLookSet.WidthDp(size, fill = false, fit = false))
    sets.add(NLookSet.HeightDp(size, fill = false, fit = false))
    style(node, sets, scope)
    // The bot's colour and the round corner land LAST, so a backdrop `bg` on the node cannot paint over the bot itself.
    val w = sizeDp(node.style["w"], where.widthDp) ?: size
    val h = sizeDp(node.style["h"], where.heightDp) ?: size
    sets.add(NLookSet.Background(fade(ink, opacity(node))))
    sets.add(NLookSet.Corner(minOf(w, h) / 2f))
    views++
    return NLookPlanNode("nl_box", sets, emptyList())
  }

  private fun shape(node: NLookNode, scope: NLookScope?): NLookPlanNode? {
    val kind = nlStr(node.props["kind"]) ?: "rect"
    val fill = nlStr(node.props["fill"])?.let { src.ink(it, scope) }
    val stroke = nlStr(node.props["stroke"])?.let { src.ink(it, scope) }
    val width = (nlNum(node.props["width"]) ?: 1.0).toFloat().coerceIn(0f, 32f)
    val w = sizeDp(node.style["w"], where.widthDp)
    val h = sizeDp(node.style["h"], where.heightDp)
    if (kind == "rect" || kind == "capsule" || kind == "circle") {
      // A plain tinted box with an outline radius: no bitmap at all, which is the cheapest thing a shape can be.
      val sets = ArrayList<NLookSet>()
      if (fill != null) sets.add(NLookSet.Background(fill))
      // A bare View measures to nothing, so a box always leaves here with both dimensions decided.
      if (node.style["w"] == null) sets.add(NLookSet.WidthDp(if (kind == "circle") 24f else null, kind != "circle", false))
      if (node.style["h"] == null) sets.add(NLookSet.HeightDp(if (kind == "circle") 24f else 8f, false, false))
      val corner = when (kind) {
        "capsule" -> (h ?: 8f) / 2f
        "circle" -> (minOf(w ?: 24f, h ?: 24f)) / 2f
        else -> (nlNum(node.style["corner"]) ?: 0.0).toFloat()
      }
      if (corner > 0f) sets.add(NLookSet.Corner(corner))
      style(node, sets, scope)
      views++
      return NLookPlanNode("nl_box", sets, emptyList())
    }
    val paths = pathsOf(node.props["d"])
    val req = NLookPaintReq(
      kind = if (kind == "dots") PAINT_DOTS else if (kind == "ring") PAINT_RING else PAINT_PATH,
      wDp = w ?: 24f, hDp = h ?: 24f, fill = fill, stroke = stroke, strokeDp = width,
      paths = paths, viewBox = boxOf(node.props["viewBox"]),
      grid = (nlInt(node.props["grid"]) ?: 0).coerceIn(0, 32),
      spacingDp = (nlNum(node.props["spacing"]) ?: 4.0).toFloat().coerceIn(1f, 64f),
      dotDp = (nlNum(node.props["dot"]) ?: 2.0).toFloat().coerceIn(0.5f, 32f),
      value = 0, of = 0, file = null, drawable = null,
      key = kind + "|" + paths.joinToString("~") + "|" + (w ?: 0f) + "x" + (h ?: 0f),
    )
    if (req.kind == PAINT_PATH && paths.isEmpty()) return null
    // A `path` is painted as a WHITE mask, so without a tint it is white on white by day and a glare at night. Its own
    // `fill`, else its `stroke`, is the tint — the colour the design asked for, in both themes. `dots` and `ring` carry
    // two colours each and are painted in them instead, so they take none.
    val mask = if (req.kind != PAINT_PATH) null else nlStr(node.props["fill"]) ?: nlStr(node.props["stroke"])
    return picture(node, req, scope, null, mask)
  }

  /**
   * THE STAGE BAR, by the one rule all three renderers follow (nlook.ts, "THE PROGRESS BAR"): one segment per stage with
   * `of` clamped to 1-8, `color` defaulting to `ink` and `track` to `line`, and the stage NAMES under it when `segments`
   * names a list holding exactly `of` of them. The names are drawn inside the bar's own picture, which is why the node
   * grows by one label row: an extra RemoteViews level for a row of text would not fit under the cap.
   */
  private fun bar(node: NLookNode, scope: NLookScope?): NLookPlanNode? {
    val value = nlInt(node.props["value"]) ?: nlInt(src.fill(nlText(node.props["value"]), scope).text) ?: 1
    val asked = nlInt(node.props["of"]) ?: nlInt(src.fill(nlText(node.props["of"]), scope).text) ?: 1
    val of = asked.coerceIn(1, 8)
    val w = sizeDp(node.style["w"], where.widthDp) ?: (where.widthDp - 32f)
    val h = sizeDp(node.style["h"], where.heightDp) ?: 4f
    val color = nlStr(node.props["color"])?.let { src.ink(it, scope) } ?: src.ink("ink", scope)
    val track = nlStr(node.props["track"])?.let { src.ink(it, scope) } ?: src.ink("line", scope)
    val labels = labels(node, of, scope)
    val req = NLookPaintReq(
      PAINT_BAR, w, h + (if (labels == null) 0f else NLookBarLabels.ROW_DP), color, track, 0f, emptyList(), null, 0, 0f, 0f,
      value.coerceIn(1, of), of, null, null,
      "bar|$value/$of|${w}x$h|" + (labels?.names?.joinToString("~") ?: ""),
      labels,
    )
    val planned = picture(node, req, scope, null)
    // What a screen reader says, as iPhone's StageBar sets its accessibility label: the stage being worked on.
    val here = labels?.names?.getOrNull(value.coerceIn(1, of) - 1)
    if (here.isNullOrEmpty()) return planned
    val sets = ArrayList<NLookSet>(planned.sets)
    sets.add(NLookSet.Describe(here))
    return NLookPlanNode(planned.layout, sets, planned.children)
  }

  /** `segments`' names, when the list holds EXACTLY `of` of them. Any other count draws the segments alone. */
  private fun labels(node: NLookNode, of: Int, scope: NLookScope?): NLookBarLabels? {
    val list = nlStr(node.props["segments"])?.trim() ?: return null
    if (list.isEmpty() || src.listCount(list) != of) return null
    val names = ArrayList<String>(of)
    for (i in 0 until of) {
      val name = src.fill("{{$list[$i]}}", scope).text
      if (name.isEmpty()) return null
      names.add(name)
    }
    return NLookBarLabels(names, src.ink("ink", scope), src.ink("meta", scope), src.ink("dim", scope))
  }

  private fun ring(node: NLookNode, scope: NLookScope?): NLookPlanNode? {
    val value = nlInt(node.props["value"]) ?: nlInt(src.fill(nlText(node.props["value"]), scope).text) ?: 0
    val of = (nlInt(node.props["of"]) ?: nlInt(src.fill(nlText(node.props["of"]), scope).text) ?: 1).coerceAtLeast(1)
    val width = (nlNum(node.props["width"]) ?: 4.0).toFloat().coerceIn(1f, 32f)
    val size = sizeDp(node.style["w"], where.widthDp) ?: sizeDp(node.style["h"], where.heightDp) ?: 32f
    val req = NLookPaintReq(
      PAINT_RING, size, size, src.ink("accent", scope), src.ink("line", scope), width, emptyList(), null, 0, 0f, 0f,
      value.coerceIn(0, of), of, null, null, "ring|$value/$of|$size|$width",
    )
    return picture(node, req, scope, null)
  }

  /**
   * The named parts today's native views already draw. They exist so a design can reuse what is already on the phone instead
   * of rebuilding it out of primitives and paying levels for it. Each one is ONE view.
   */
  private fun kit(node: NLookNode, level: Int, scope: NLookScope?): NLookPlanNode? {
    val name = nlStr(node.props["name"]) ?: return null
    val w = sizeDp(node.style["w"], where.widthDp)
    val h = sizeDp(node.style["h"], where.heightDp)
    // A kit part may carry props of its own, under `props` (nlook.ts NLOOK_PROPS.Kit).
    val own = node.props["props"] as? Map<*, *>
    return when (name) {
      "mark" -> {
        views++
        val sets = ArrayList<NLookSet>()
        sets.add(NLookSet.Paint(NLookPaintReq(PAINT_ART, w ?: 24f, h ?: 24f, null, null, 0f, emptyList(), null, 0, 0f, 0f, 0, 0, null, "tailzu_widget_mark", "kit.mark")))
        style(node, sets, scope)
        NLookPlanNode("nl_img_fit", sets, emptyList())
      }
      "pill" -> {
        views++
        val sets = ArrayList<NLookSet>()
        (src.ink("surface", scope))?.let { sets.add(NLookSet.Background(it)) }
        sets.add(NLookSet.Corner(((h ?: 34f) / 2f)))
        style(node, sets, scope)
        NLookPlanNode("nl_box", sets, emptyList())
      }
      "askBar" -> askBar(node, level, h, scope)
      "beads", "stripes" -> {
        // THE WEEK'S BEADS, as today's view draws them: `value` filled in ink, then ONE hollow one after. The value is
        // the kit part's own prop, usually "{{week.dots}}"; without one the row is five filled beads, which is what a
        // plain `stripes` is. Reading it was missing, so every bead row came out five filled whatever the week held.
        val asked = nlInt(own?.get("value")) ?: nlInt(src.fill(nlText(own?.get("value")), scope).text)
        val filled = (asked ?: 5).coerceIn(0, 5)
        val total = if (asked == null) filled else filled + 1
        if (total <= 0) return null
        val req = NLookPaintReq(
          PAINT_DOTS, w ?: 60f, h ?: 8f, src.ink("ink", scope), src.ink("hollow", scope), 0f, emptyList(), null,
          total, 10f, 3f,
          // `of` 0 is a plain row, every bead filled; `of` set is a value row, `value` filled and the rest hollow.
          if (asked == null) 0 else filled, if (asked == null) 0 else total,
          null, null, "kit.$name|$filled/$total|${w ?: 0f}x${h ?: 0f}",
        )
        picture(node, req, scope, null)
      }
      else -> null
    }
  }

  /**
   * ASK, the bar at the foot of today's X0: the word in `meta` on a `surface` capsule, Blip's peek key at its end, the
   * capsule opening the ask screen and the key opening the mic. It used to plan as a bare `nl_box` — a grey capsule
   * with nothing in it, which is not a part of the kit, it is a hole where one should be.
   *
   * ONE extra level (an H holding three leaves) and four views. Over the cap it draws what today's `pill` drew, so a
   * deep design loses the words rather than the whole tile.
   */
  private fun askBar(node: NLookNode, level: Int, h: Float?, scope: NLookScope?): NLookPlanNode? {
    val sets = ArrayList<NLookSet>()
    (src.ink("surface", scope))?.let { sets.add(NLookSet.Background(it)) }
    sets.add(NLookSet.Corner(((h ?: 34f) / 2f)))
    style(node, sets, scope)
    views++
    val plain = NLookPlanNode("nl_box", sets, emptyList())
    if (level + 1 > levels || views + 3 > NLookLimits.VIEWS_PER_SIZE) return plain

    val kids = ArrayList<NLookPlanNode>()
    val words = src.fill("{{words.ask}}", scope).text
    if (words.isNotEmpty()) {
      val text = ArrayList<NLookSet>()
      text.add(NLookSet.Words(words))
      text.add(NLookSet.TextSizeDp(14f))
      src.ink("meta", scope)?.let { text.add(NLookSet.TextColor(it)) }
      text.add(NLookSet.MaxLines(1))
      text.add(NLookSet.TextAlign("start"))
      text.add(NLookSet.MarginDp(14f, 0f))
      views++
      kids.add(NLookPlanNode(textLayout("sans", 400, false), text, emptyList()))
    }
    views++
    kids.add(NLookPlanNode("nl_spacer_h", emptyList(), emptyList()))

    val key = ArrayList<NLookSet>()
    val keyDp = ((h ?: 34f) - 2f).coerceIn(20f, 36f)
    key.add(NLookSet.Paint(NLookPaintReq(PAINT_ART, keyDp, keyDp, null, null, 0f, emptyList(), null, 0, 0f, 0f, 0, 0, null, "tailzu_x0_peek", "kit.askKey")))
    key.add(NLookSet.WidthDp(keyDp, fill = false, fit = false))
    key.add(NLookSet.HeightDp(keyDp, fill = false, fit = false))
    // The mic link when the glance carries one, else the ask screen — the same order today's view uses.
    link(src.fill("{{links.mic}}", scope).text)?.let { key.add(NLookSet.Click(it)) }
    views++
    kids.add(NLookPlanNode("nl_img_fit", key, emptyList()))

    // The capsule itself opens Ask. Added last so it lands after the node's own style.
    val outer = ArrayList<NLookSet>(sets)
    link(src.fill("{{links.ask}}", scope).text)?.let { outer.add(NLookSet.Click(it)) }
    return NLookPlanNode("nl_h_center", outer, kids)
  }

  /** One of the kit's own links, checked by the same allow-list a design's Button goes through. */
  private fun link(open: String): NLookClick? {
    val url = open.ifEmpty { ASK_LINK }
    if (!allowedLink(url)) return null
    slot++
    return NLookClick(url, null, null, slot)
  }

  /**
   * An ImageView fragment carrying a paint request, with the node's own style over it. `fit` picks the fragment, because
   * ImageView.setScaleType takes an enum and is not remotable: the kit has one image fragment per fit.
   */
  private fun picture(
    node: NLookNode,
    req: NLookPaintReq,
    scope: NLookScope?,
    square: Float?,
    /** The colour to use when the node names no `tint` of its own: only a `sym:` glyph has one (it reads as a label). */
    otherwise: String? = null,
  ): NLookPlanNode {
    views++
    paints.add(req)
    val sets = ArrayList<NLookSet>()
    sets.add(NLookSet.Paint(req))
    if (square != null) {
      sets.add(NLookSet.WidthDp(square, fill = false, fit = false))
      sets.add(NLookSet.HeightDp(square, fill = false, fit = false))
    }
    (nlStr(node.props["tint"]) ?: otherwise)?.let { token -> src.ink(token, scope)?.let { sets.add(NLookSet.Tint(it)) } }
    val fade = opacity(node)
    if (fade < 1f) sets.add(NLookSet.ImageAlpha(fade))
    style(node, sets, scope)
    val layout = when {
      req.kind == PAINT_BAR -> "nl_bar"
      else -> "nl_img_" + when (nlStr(node.props["fit"])) {
        "fill" -> "fill"
        "stretch" -> "stretch"
        else -> "fit"
      }
    }
    return NLookPlanNode(layout, sets, emptyList())
  }

  // ---------------------------------------------------------------- style and conditions

  /** The style keys format 1 promises. An unknown key is simply not read: that is the whole of the rule. */
  private fun style(node: NLookNode, sets: ArrayList<NLookSet>, scope: NLookScope?) {
    val s = node.style
    if (s.isEmpty()) return
    nlPad(s["pad"])?.let { sets.add(NLookSet.PadDp(it)) }
    size(s["w"], true, sets)
    size(s["h"], false, sets)
    nlStr(s["bg"])?.let { token -> src.ink(token, scope)?.let { sets.add(NLookSet.Background(fade(it, opacity(node)))) } }
    nlNum(s["corner"])?.let { sets.add(NLookSet.Corner(it.toFloat().coerceIn(0f, 120f))) }
    // THE FOUR KEYS NOT SET HERE, and where each one is instead:
    //   offset     iOS only. RemoteViews has no free offset, and faking it with margins would move the layout, not the
    //              paint. The contract says so too (nlook.ts), so this is a recorded gap and not a surprise.
    //   maxW/maxH  on a Text or a timer, through `ceiling` — TextView.setMaxWidth and setMaxHeight ARE remotable. On a
    //              frame the same call throws inside the launcher, so every other node is left to `w`/`h`.
    //   opacity    folded into the colours above and into a picture's own alpha, never View.setAlpha (see ImageAlpha).
    //   border     one wrapper level, in `bordered`, once the node is planned and its real depth is known.
  }

  /** `opacity`, 1 when there is none. */
  private fun opacity(node: NLookNode): Float = (nlNum(node.style["opacity"]) ?: 1.0).toFloat().coerceIn(0f, 1f)

  /** A colour at a share of its own alpha, both themes. Pure: the planner never touches android.graphics. */
  private fun fade(ink: NLookInk, share: Float): NLookInk {
    if (share >= 1f) return ink
    return NLookInk(fade(ink.light, share), fade(ink.dark, share))
  }

  private fun fade(color: Int, share: Float): Int {
    val a = (((color ushr 24) and 0xFF) * share).toInt().coerceIn(0, 255)
    return (color and 0x00FFFFFF) or (a shl 24)
  }

  private fun size(v: Any?, horizontal: Boolean, sets: ArrayList<NLookSet>) {
    val s = nlStr(v)
    val fill = s == "fill"
    val fit = s == "fit"
    val dp = nlNum(v)?.toFloat()?.coerceIn(0f, 2000f)
    if (!fill && !fit && dp == null) return
    if (horizontal) sets.add(NLookSet.WidthDp(dp, fill, fit)) else sets.add(NLookSet.HeightDp(dp, fill, fit))
  }

  private fun sizeDp(v: Any?, whole: Float): Float? {
    nlNum(v)?.let { return it.toFloat().coerceIn(0f, 2000f) }
    return if (nlStr(v) == "fill") (whole - 32f).coerceAtLeast(8f) else null
  }

  /** `if`: an AND over keys, each key an OR over its values. An unknown key is ignored, so a later design still shows. */
  private fun matches(cond: Map<String, Any?>?, scope: NLookScope?): Boolean {
    if (cond == null || cond.isEmpty()) return true
    for (entry in cond) {
      val ok = when (entry.key) {
        "family" -> any(entry.value, where.family)
        "appearance" -> any(entry.value, if (where.night) "dark" else "light")
        "platform" -> any(entry.value, "android")
        "case" -> any(entry.value, where.case)
        "canAnswer" -> nlBool(entry.value) == where.canAnswer
        // iOS's own: a widget on an Android home screen is always full colour, never Always-On, never on a Lock Screen.
        "mode" -> any(entry.value, "full")
        "reduced" -> nlBool(entry.value) == false
        "standby" -> nlBool(entry.value) == false
        "has" -> nlStr(entry.value)?.let { src.has(it, scope) } ?: true
        // phase is the Live Activity's, which Android has no widget equivalent of; and anything unknown is ignored.
        else -> true
      }
      if (!ok) return false
    }
    return true
  }

  private fun any(value: Any?, actual: String): Boolean {
    val list = nlList(value)
    if (list.isEmpty()) return true
    for (v in list) if (nlStr(v) == actual) return true
    return false
  }

  companion object {
    const val AXIS_V = 0
    const val AXIS_H = 1
    const val AXIS_Z = 2

    /** A bot slug, as the glance and the art keys spell one. */
    private val BOT_SLUG = Regex("^[a-z0-9][a-z0-9_-]{0,47}$")

    /**
     * Which text fragment draws this. setTypeface is NOT remotable and auto-size is not either, so a fragment exists per
     * (face, weight, autosize) and the generator writes them all. This `when` is the matching half of FACES in
     * android/nlook-layouts.py: change one and change the other, or a design names a layout the build does not hold and
     * the whole draw falls back to today's views.
     *
     * The three bundled faces are STATIC files (android/fonts/README.md), one per real weight, so each resolves to the
     * weight there is a file for rather than to a synthetic bold. A face with no file at all still falls to `sans`,
     * exactly as the contract says a font that cannot register does.
     */
    fun textLayout(font: String?, weight: Int, auto: Boolean): String {
      val tail = if (auto) "_auto" else ""
      val w = when {
        weight >= 800 -> 800
        weight >= 700 -> 700
        weight >= 600 -> 600
        weight >= 500 -> 500
        else -> 400
      }
      return when (font) {
        "mono" -> "nl_t_mono_" + w + tail
        // Geist Medium under 600, Geist SemiBold at 600 and up: the two weights there are files for.
        "brand" -> "nl_t_brand_" + (if (w >= 600) 600 else 500) + tail
        "display" -> "nl_t_display_600" + tail
        "dots" -> "nl_t_dots_400" + tail
        else -> "nl_t_sans_" + w + tail
      }
    }

    /** Where Ask opens when the glance names no link of its own, as today's views have it (TailzuX0Widget). */
    const val ASK_LINK = "tulmi://screen/bots.ask"

    /** Only our own scheme, and the one https shape today's allow-list permits. Checked again in NLookRemote. */
    fun allowedLink(url: String): Boolean {
      val s = url.trim()
      if (s.startsWith("tulmi://")) return true
      return s.startsWith("https://github.com/") && !s.contains(" ")
    }

    /** The `d` strings of a Shape: at most 12 paths, each at most 900 characters. A longer one drops alone. */
    fun pathsOf(v: Any?): List<String> {
      val out = ArrayList<String>()
      for (entry in nlList(v)) {
        if (out.size >= NLookLimits.PATHS_PER_SHAPE) break
        val d = nlStr(entry) ?: continue
        if (d.isEmpty() || d.length > NLookLimits.PATH_CHARS) continue
        out.add(d)
      }
      return out
    }

    fun boxOf(v: Any?): FloatArray? {
      val list = v as? List<*> ?: return null
      if (list.size != 4) return null
      val out = FloatArray(4)
      for (i in 0 until 4) out[i] = (nlNum(list[i]) ?: return null).toFloat()
      return if (out[2] > 0f && out[3] > 0f) out else null
    }

    /** How deep a plan is, in RemoteViews levels. The tests assert this against the cap. */
    fun depth(node: NLookPlanNode): Int {
      var deepest = 0
      for (kid in node.children) {
        val d = depth(kid)
        if (d > deepest) deepest = d
      }
      return deepest + 1
    }

    /** How many views a plan holds. */
    fun size(node: NLookPlanNode): Int {
      var n = 1
      for (kid in node.children) n += size(kid)
      return n
    }

    private fun trim2(v: Double): String {
      val r = Math.round(v * 100.0) / 100.0
      val s = r.toString()
      return if (s.endsWith(".0")) s.substring(0, s.length - 2) else s
    }
  }
